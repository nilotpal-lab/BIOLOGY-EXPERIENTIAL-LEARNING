/**
 * convert-fw-pond1.mjs
 *
 * Reproducible converter for the first freshwater research network (RES-FW-A).
 *
 * Source archive: doi_10_5061_dryad_866t1g1zj__v20240507.zip
 * Inside it: FoodwebMetadata.zip -> FoodwebMetadata/communities/Pond1/
 *            nodes.csv, trophic.links.csv, properties.csv
 * Those three files are committed verbatim in ./source-fw-pond1/.
 *
 * Run: node src/data/research/convert-fw-pond1.mjs
 */
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { buildPondDataset } from './pondConversion.mjs'
import { report, writeDatasetModule } from './sourceUtils.mjs'

const here = dirname(fileURLToPath(import.meta.url))
const sourceDir = join(here, 'source-fw-pond1')

const { dataset: built, counts } = buildPondDataset({
  sourceDir,
  idPrefix: 'fw-a',
  pondFolder: 'Pond1',
})

const dataset = {
  id: 'RES-FW-A',
  name: `RES-FW-A · Shallow-lake mesocosm (${built.pondLabel}, heated + insecticide)`,
  ecosystem: 'freshwater',
  summary:
    `Single shallow-lake mesocosm food web (${built.pondLabel} / ${built.pondCode}; ${built.treatment}) from a three-stressor experiment. ` +
    'Nodes are documented groups of organisms, not species. Treatment-summed webs in the same archive are aggregates of these same ponds and are not counted as separate networks.',
  isDemo: false,
  sourceStatus: 'research-verified',
  provenance: {
    origin:
      'Zhang P, Zhang H, Xu J. "Multiple stressors simplify freshwater food webs." Dryad dataset doi:10.5061/dryad.866t1g1zj (v5, published 2024-05-07). Community file: FoodwebMetadata/communities/Pond1 (Pondcode WI1).',
    citation:
      'Zhang P, Zhang H, Xu J (2024). Data from: Multiple stressors simplify freshwater food webs. Dryad dataset doi:10.5061/dryad.866t1g1zj. Related article: doi:10.1111/gcb.70114.',
    sourceUrl: 'https://doi.org/10.5061/dryad.866t1g1zj',
    license:
      'CC0 1.0 Universal (public-domain dedication), as recorded on the Dryad record for doi:10.5061/dryad.866t1g1zj. Redistribution of the derived network is permitted under those terms.',
    version: 'v20240507 (Dryad dataset version 5)',
    nodeUnit:
      'Groups of organisms (source README: "each node represents a group of organisms in the food web"), not species.',
    cleaningNotes: [
      'Extracted exactly one documented community: FoodwebMetadata/communities/Pond1 (properties.csv: title=Pond1, Pondcode=WI1, Temp=W, Eutroph=0, Pesticide=I). No treatment-summed web was used.',
      'The three source CSVs are committed verbatim in src/data/research/source-fw-pond1/ so this conversion is reproducible with node src/data/research/convert-fw-pond1.mjs.',
      'Link direction follows the archive README: trophic.links.csv "resource: the food for the consumer" and "consumer: the consumer of the food", i.e. resource -> consumer. No reversal was needed.',
      'Node names were slugged into stable ids (fw-a-<slug>); the original node name is kept in originalId and sourceNote.',
      'Trophic role comes from the source category / functional.group columns and is marked roleEvidence: "documented". Mapping to the app vocabulary: producer -> producer, herbivore -> primary-consumer, Omnivore -> omnivore.',
      'Only the 18 recorded resource -> consumer rows were kept. The converter throws if a duplicate link, a self-link or an endpoint missing from nodes.csv appears.',
      'Quantitative columns (mean body mass M, abundance N, total biomass) are preserved in sourceNote. They are NOT used as link weights because the app model is an unweighted directed graph.',
    ],
    validationStatus: 'research-verified',
    retrievedOn: '2026-10-18',
  },
  nodes: built.nodes,
  edges: built.edges,
}

writeDatasetModule({
  outPath: join(here, 'FW-A.ts'),
  exportName: 'RES_FW_A',
  title: `RES-FW-A — shallow-lake mesocosm (${built.pondLabel}, heated + insecticide)`,
  headerLines: [
    'Generated by convert-fw-pond1.mjs from source-fw-pond1/{nodes,trophic.links,properties}.csv,',
    'which are the verbatim contents of Dryad doi:10.5061/dryad.866t1g1zj',
    '(FoodwebMetadata.zip -> FoodwebMetadata/communities/Pond1).',
  ],
  dataset,
})

report('RES-FW-A', [
  `source rows: ${counts.rawNodeRows} nodes, ${counts.rawLinkRows} links`,
  `accepted:   ${counts.acceptedNodes} nodes, ${counts.acceptedLinks} links`,
  'rejected:   0 rows (the converter throws instead of dropping silently)',
])
