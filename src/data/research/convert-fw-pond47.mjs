/**
 * convert-fw-pond47.mjs
 *
 * Converter for the second freshwater research network (RES-FW-B).
 *
 * Source archive: doi_10_5061_dryad_866t1g1zj__v20240507.zip
 * Inside it: FoodwebMetadata.zip -> FoodwebMetadata/communities/Pond47/
 *            nodes.csv, trophic.links.csv, properties.csv  (Pondcode C6)
 * Those three files are committed verbatim in ./source-fw-pond47/.
 *
 * Pond 47 is a fourth unheated control replicate of the same 48-pond mesocosm
 * experiment that produced RES-FW-A (Pond 1). It is a distinct food-web
 * instance with its own sampled community, but it is NOT an independent
 * ecosystem or an independent study — the provenance says so explicitly.
 *
 * Run: node src/data/research/convert-fw-pond47.mjs
 */
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { buildPondDataset } from './pondConversion.mjs'
import { report, writeDatasetModule } from './sourceUtils.mjs'

const here = dirname(fileURLToPath(import.meta.url))
const sourceDir = join(here, 'source-fw-pond47')

const { dataset: built, counts } = buildPondDataset({
  sourceDir,
  idPrefix: 'fw-b',
  pondFolder: 'Pond47',
})

const dataset = {
  id: 'RES-FW-B',
  name: `RES-FW-B · Shallow-lake mesocosm (${built.pondLabel}, ambient control)`,
  ecosystem: 'freshwater',
  summary:
    `Unheated, untreated control mesocosm food web (${built.pondLabel} / ${built.pondCode}) from the same 48-pond three-stressor experiment as RES-FW-A. ` +
    'A separate sampled community and a separate network, but an experimental replicate rather than an independent ecosystem or study.',
  isDemo: false,
  sourceStatus: 'research-verified',
  provenance: {
    origin:
      'Zhang P, Zhang H, Xu J. "Multiple stressors simplify freshwater food webs." Dryad dataset doi:10.5061/dryad.866t1g1zj (v5, published 2024-05-07). Community file: FoodwebMetadata/communities/Pond47 (Pondcode C6).',
    citation:
      'Zhang P, Zhang H, Xu J (2024). Data from: Multiple stressors simplify freshwater food webs. Dryad dataset doi:10.5061/dryad.866t1g1zj. Related article: doi:10.1111/gcb.70114.',
    sourceUrl: 'https://doi.org/10.5061/dryad.866t1g1zj',
    license:
      'CC0 1.0 Universal (public-domain dedication), as recorded on the Dryad record for doi:10.5061/dryad.866t1g1zj. Redistribution of the derived network is permitted under those terms.',
    version: 'v20240507 (Dryad dataset version 5)',
    nodeUnit:
      'Groups of organisms (source README: "each node represents a group of organisms in the food web"), not species.',
    cleaningNotes: [
      'Extracted exactly one documented community: FoodwebMetadata/communities/Pond47 (properties.csv: title=Pond47, Pondcode=C6, Temp=0, Eutroph=0, Pesticide=0 — an unheated, untreated control).',
      'Relationship to RES-FW-A: both networks come from the same mesocosm experiment (48 ponds, 8 treatments x 6 replicates). This is a replicate network instance, not an independent ecosystem, and the app does not claim study-level independence for the freshwater pair.',
      'The three source CSVs are committed verbatim in src/data/research/source-fw-pond47/ so this conversion is reproducible with node src/data/research/convert-fw-pond47.mjs.',
      'Link direction follows the archive README: resource = the food for the consumer, consumer = the consumer of the food, i.e. resource -> consumer.',
      'Node names were slugged into stable ids (fw-b-<slug>); the original node name is kept in originalId and sourceNote.',
      'Trophic role comes from the source category / functional.group columns and is marked roleEvidence: "documented". Mapping: producer -> producer, herbivore -> primary-consumer, Omnivore -> omnivore.',
      'Only the recorded resource -> consumer rows were kept. The converter throws if a duplicate link, a self-link or an endpoint missing from nodes.csv appears.',
      'Quantitative columns (mean body mass M, abundance N, total biomass) are preserved in sourceNote and are not used as link weights.',
    ],
    validationStatus: 'research-verified',
    retrievedOn: '2026-10-18',
  },
  nodes: built.nodes,
  edges: built.edges,
}

writeDatasetModule({
  outPath: join(here, 'FW-B.ts'),
  exportName: 'RES_FW_B',
  title: `RES-FW-B — shallow-lake mesocosm (${built.pondLabel}, ambient control)`,
  headerLines: [
    'Generated by convert-fw-pond47.mjs from source-fw-pond47/{nodes,trophic.links,properties}.csv,',
    'which are the verbatim contents of Dryad doi:10.5061/dryad.866t1g1zj',
    '(FoodwebMetadata.zip -> FoodwebMetadata/communities/Pond47).',
  ],
  dataset,
})

report('RES-FW-B', [
  `source rows: ${counts.rawNodeRows} nodes, ${counts.rawLinkRows} links`,
  `accepted:   ${counts.acceptedNodes} nodes, ${counts.acceptedLinks} links`,
  'rejected:   0 rows (the converter throws instead of dropping silently)',
])
